/**
 * Returns tab entity types enabled for a specific event workbook template
 */
export function getTabsForTemplate(templateKey: WorkbookTemplateKey): TabEntityType[] {
  switch (templateKey) {
    case 'CONFERENCE': // MUN, Model UN, Summits
      return [
        'DASHBOARD',
        'EVENT_CONFIG',
        'TEAM_SECRETARIAT',
        'COMMITTEES_ROLES',
        'RECRUITMENT',
        'APPLICATIONS',
        'ALLOCATIONS',
        'REGISTRATIONS',
        'ATTENDANCE',
        'TASKS_OPERATIONS',
        'PAYMENTS_SUMMARY',
        'AUDIT_SYNC_LOG',
      ];
    case 'COMPETITION': // Debates, Moot Courts
      return [
        'DASHBOARD',
        'EVENT_CONFIG',
        'TEAM_SECRETARIAT',
        'COMMITTEES_ROLES',
        'RECRUITMENT',
        'APPLICATIONS',
        'ALLOCATIONS',
        'REGISTRATIONS',
        'TASKS_OPERATIONS',
        'AUDIT_SYNC_LOG',
      ];
    case 'WORKSHOP': // Hackathons, Tech Summits
      return [
        'DASHBOARD',
        'EVENT_CONFIG',
        'TEAM_SECRETARIAT',
        'RECRUITMENT',
        'APPLICATIONS',
        'ALLOCATIONS',
        'REGISTRATIONS',
        'TASKS_OPERATIONS',
        'PAYMENTS_SUMMARY',
        'AUDIT_SYNC_LOG',
      ];
    case 'TALENT_SHOW':
    case 'FESTIVAL':
      return [
        'DASHBOARD',
        'EVENT_CONFIG',
        'TEAM_SECRETARIAT',
        'RECRUITMENT',
        'APPLICATIONS',
        'REGISTRATIONS',
        'ATTENDANCE',
        'TASKS_OPERATIONS',
        'AUDIT_SYNC_LOG',
      ];
    case 'CUSTOM':
    default:
      return [
        'DASHBOARD',
        'EVENT_CONFIG',
        'TEAM_SECRETARIAT',
        'COMMITTEES_ROLES',
        'RECRUITMENT',
        'APPLICATIONS',
        'ALLOCATIONS',
        'REGISTRATIONS',
        'ATTENDANCE',
        'TASKS_OPERATIONS',
        'PAYMENTS_SUMMARY',
        'AUDIT_SYNC_LOG',
        'CUSTOM',
      ];
  }
}
