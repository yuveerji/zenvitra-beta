export function lookupFlag(name: string): string {
  const clean = name.toLowerCase().replace(/^(the|republic of|delegate of|delegation of)\s+/g, '').trim();
  if (COUNTRY_FLAG_MAP[clean]) return COUNTRY_FLAG_MAP[clean];
  for (const [key, flag] of Object.entries(COUNTRY_FLAG_MAP)) {
    if (clean === key || clean.includes(key) || key.includes(clean)) return flag;
  }
  return '🌐';
}

