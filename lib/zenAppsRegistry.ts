// Helper functions for easy querying
export function getModulesForApp(appId: string): ZenAppModule[] {
  return ZEN_APP_MODULES.filter((m) => m.parentAppId === appId);
}

export function getAppForModule(moduleId: string): ZenAppItem | undefined {
  const mod = ZEN_APP_MODULES.find((m) => m.id === moduleId);
  if (!mod) return undefined;
  return ZEN_APPS_REGISTRY.find((a) => a.id === mod.parentAppId);
}

