export function parsePastedList(text: string): PresetDelegation[] {
  if (!text || !text.trim()) return [];
  const items = text
    .split(/[\n,;\r]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);

  return items.map((raw) => {
    const emojiMatch = raw.match(/([\uD800-\uDBFF][\uDC00-\uDFFF]|[\u2600-\u27BF])/);
    const flag = emojiMatch ? emojiMatch[0] : lookupFlag(raw);
    const cleanName = raw.replace(/([\uD800-\uDBFF][\uDC00-\uDFFF]|[\u2600-\u27BF])/g, '').trim();

    return {
      country: cleanName || raw,
      flag,
    };
  });
}

export function parseCsvOrText(rawText: string): PresetDelegation[] {
  if (!rawText || !rawText.trim()) return [];

  const lines = rawText.split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const results: PresetDelegation[] = [];

  for (const line of lines) {
    // Detect delimiters: tab, comma, semicolon
    const parts = line.includes('\t')
      ? line.split('\t')
      : line.includes(';')
      ? line.split(';')
      : line.split(',');

    const firstCol = parts[0]?.replace(/^["']|["']$/g, '').trim();
    const secondCol = parts[1]?.replace(/^["']|["']$/g, '').trim();

    if (!firstCol) continue;
    // Skip common CSV headers
    const lower = firstCol.toLowerCase();
    if (lower === 'country' || lower === 'delegation' || lower === 'portfolio' || lower === 'state' || lower === 's.no' || lower === 'sr. no' || lower === 'id') {
      continue;
    }

    const flag = lookupFlag(firstCol);
    results.push({
      country: firstCol,
      flag,
      subTitle: secondCol && secondCol.length > 1 ? secondCol : undefined,
    });
  }

  return results;
}

export function parseGoogleSheetsShareUrl(url: string): string | null {
  if (!url || typeof url !== 'string') return null;
  const match = url.match(/\/spreadsheets\/d\/([a-zA-Z0-9-_]+)/);
  if (!match || !match[1]) return null;
  const sheetId = match[1];

  // Extract gid if available
  const gidMatch = url.match(/[#&?]gid=([0-9]+)/);
  const gid = gidMatch ? gidMatch[1] : '0';

  return `https://docs.google.com/spreadsheets/d/${sheetId}/export?format=csv&gid=${gid}`;
}
