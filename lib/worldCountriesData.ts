export function searchWorldCountries(query: string): WorldCountryEntity[] {
  if (!query || !query.trim()) return ALL_WORLD_COUNTRIES_AND_REGIONS;
  const q = query.toLowerCase().trim();
  return ALL_WORLD_COUNTRIES_AND_REGIONS.filter(
    (c) => c.name.toLowerCase().includes(q) || (c.code && c.code.toLowerCase().includes(q))
  );
}
