import React from 'react';

export type AppDevelopmentStatus = 'Live' | 'In Development' | 'Planned' | 'Coming Soon';

export type ExplorationLevel = 
  | 'CORE'           // Level 0: Central Core & Primary 7 Sector boundaries
  | 'APPS'           // Level 1: Primary Application Nodes
  | 'MODULES'        // Level 2: Internal Application Modules
  | 'INFRASTRUCTURE' // Level 3: Shared Infrastructure & Data Network
  | 'UNIVERSE';      // Level 4: External Gateways & Cross-Application Workflows

export type EcosystemClusterId = 
  | 'communication'
  | 'social_community'
  | 'identity_recognition'
  | 'mun_events'
  | 'documents_creation'
  | 'civic_impact'
  | 'core_platform';

export interface EcosystemCluster {
  id: EcosystemClusterId;
  name: string;
  shortName: string;
  tagline: string;
  description: string;
  accentColor: string; // e.g. '#3b82f6'
  accentGlow: string; // e.g. 'rgba(59, 130, 246, 0.4)'
  badgeClass: string;
  borderClass: string;
  startAngleDeg: number;
  endAngleDeg: number;
  centerAngleDeg: number;
}

export interface SharedPlatformService {
  id: string;
  name: string;
  category: 'INFRASTRUCTURE';
  description: string;
  status: AppDevelopmentStatus;
  angleDeg: number;
  radiusPercent: number; // radius inside middle ring (e.g. 23%)
  features: string[];
  dependentAppIds: string[];
}

export interface ZenAppModule {
  id: string;
  name: string;
  shortName: string;
  parentAppId: string;
  clusterId: EcosystemClusterId;
  description: string;
  status: AppDevelopmentStatus;
  iconName: string;
  capabilities: string[];
  route?: string;
  angleDeg: number;
  radiusPercent: number; // radial distance on module satellite orbit ring (e.g. 54-62%)
}

export interface UniverseIntegration {
  id: string;
  name: string;
  category: 'GATEWAY' | 'PROTOCOL' | 'MEDIA' | 'LEDGER';
  description: string;
  status: AppDevelopmentStatus;
  iconName: string;
  angleDeg: number;
  radiusPercent: number; // outer cosmos orbit (e.g. 70-78%)
  connectedAppIds: string[];
  isExternal?: boolean;
  externalUrl?: string;
  capabilities: string[];
}

export interface CrossWorkflowLink {
  id: string;
  name: string;
  sourceId: string;
  targetId: string;
  description: string;
  accentColor: string;
}

export interface ZenAppItem {
  id: string;
  name: string;
  shortName: string;
  clusterId: EcosystemClusterId;
  tagline: string;
  description: string;
  status: AppDevelopmentStatus;
  iconName: string;
  capabilities: string[];
  route?: string; // Verified existing route in Zenvitra (e.g. '/chat', '/pulse')
  connections: string[]; // Connected ZenApp IDs
  dependencies: string[]; // Platform services it relies on
  primaryActionLabel?: string;
  radiusPercent: number; // Distance from center: ~38% (inner cluster ring) or ~47% (outer cluster ring)
  angleDeg: number; // Specific radial angle on 360 circle
}

